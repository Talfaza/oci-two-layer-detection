#!/usr/bin/env python3
"""Aggregate the corpus verdict logs into results/corpus/report.md.

Reads clean_verdicts.csv (false-positive rate) and stego_verdicts.csv
(recall, broken down per construction factor) and emits a reviewer-facing
markdown report with Wilson 95% confidence intervals. See
docs/corpus-evaluation.md.
"""
import csv
import math
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CDIR = os.path.join(ROOT, "results", "corpus")
CLEAN = os.path.join(CDIR, "clean_verdicts.csv")
STEGO = os.path.join(CDIR, "stego_verdicts.csv")
REPORT = os.path.join(CDIR, "report.md")


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    hw = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (p, (c - hw) / d, (c + hw) / d)


def read(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def breakdown(rows, key):
    agg = defaultdict(lambda: [0, 0])
    for r in rows:
        a = agg[r[key]]
        a[0] += int(r["detected"])
        a[1] += 1
    out = []
    for k in sorted(agg):
        det, tot = agg[k]
        p, lo, hi = wilson(det, tot)
        out.append((k, det, tot, p, lo, hi))
    return out


def main():
    clean = read(CLEAN)
    stego = read(STEGO)
    L = []

    L.append("# Corpus evaluation report\n")
    L.append("Auto-generated by `experiments/corpus/analyze.py`. "
             "CIs are Wilson 95%.\n")

    # ---- false positives ----
    L.append("## False-positive rate (clean corpus)\n")
    if clean:
        fp = sum(1 for r in clean if int(r["high_count"]) > 0)
        n = len(clean)
        p, lo, hi = wilson(fp, n)
        L.append(f"- Images scanned: **{n}**")
        L.append(f"- False positives: **{fp}**")
        L.append(f"- FPR: **{p*100:.2f}%** (95% CI {lo*100:.2f}–{hi*100:.2f}%)\n")
        cats = defaultdict(lambda: [0, 0])
        for r in clean:
            c = cats[r["category"]]
            c[0] += int(int(r["high_count"]) > 0)
            c[1] += 1
        L.append("| Category | Images | FP |")
        L.append("|---|---|---|")
        for c in sorted(cats):
            fpn, tot = cats[c]
            L.append(f"| {c} | {tot} | {fpn} |")
        L.append("")
        fps = [r for r in clean if int(r["high_count"]) > 0]
        if fps:
            L.append("### False positives (allowlist candidates)\n")
            L.append("| Image | Kinds | Detail |")
            L.append("|---|---|---|")
            for r in fps:
                L.append(f"| `{r['image']}` | {r['kinds']} | {r['detail'][:80]} |")
            L.append("")
    else:
        L.append("_No clean_verdicts.csv yet — run run_clean.py._\n")

    # ---- recall ----
    L.append("## Detection rate (stego corpus)\n")
    if stego:
        det = sum(int(r["detected"]) for r in stego)
        n = len(stego)
        p, lo, hi = wilson(det, n)
        L.append(f"- Stego variants: **{n}**")
        L.append(f"- Detected (>=1 HIGH): **{det}**")
        L.append(f"- Recall: **{p*100:.2f}%** (95% CI {lo*100:.2f}–{hi*100:.2f}%)")
        nb = len({r['base'] for r in stego})
        L.append(f"- Distinct base images: **{nb}**\n")
        for key, title in [("family", "carrier family"),
                           ("payload_size", "payload size (bytes)"),
                           ("entropy", "payload entropy"),
                           ("whiteout_style", "whiteout style"),
                           ("depth", "hide depth (layers)"),
                           ("category", "base category")]:
            L.append(f"### Recall by {title}\n")
            L.append("| Value | Detected | Total | Recall | 95% CI |")
            L.append("|---|---|---|---|---|")
            for k, d, t, pp, lo2, hi2 in breakdown(stego, key):
                L.append(f"| {k} | {d} | {t} | {pp*100:.1f}% | "
                         f"{lo2*100:.1f}–{hi2*100:.1f}% |")
            L.append("")
        # the honest crossover: appended is expected to be missed by static
        app = [r for r in stego if r["family"] == "appended"]
        if app:
            miss = sum(1 for r in app if not int(r["detected"]))
            L.append(f"> **Crossover check:** {miss}/{len(app)} appended-carrier "
                     f"variants are missed by the static layer (expected: the "
                     f"content-embedded family is the dynamic layer's job).\n")
    else:
        L.append("_No stego_verdicts.csv yet — run gen_stego.py._\n")

    open(REPORT, "w").write("\n".join(L))
    print("\n".join(L))
    print(f"\n[=] written -> {REPORT}")


if __name__ == "__main__":
    main()
