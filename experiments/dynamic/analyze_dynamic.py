#!/usr/bin/env python3
"""Aggregate results/dynamic/ratio.csv into results/dynamic/report.md.

Produces (a) an ROC over the read:write threshold using the live hunt.bt signal
(falling back to the simulated read+pread+mmap signal without --live data),
(b) a per-strategy evasion table across detector generations, (c) the tail-read
gap of the ratio by payload size, (d) the benign noise floor, and (e) the
combined ratio + provenance verdict (STEGO-EXTRACTION or STEGO-DECODE), with the
embedded-payload loader as a separate FP class. See docs/dynamic-detection.md.
"""
import csv
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CSV = os.path.join(ROOT, "results", "dynamic", "ratio.csv")
REPORT = os.path.join(ROOT, "results", "dynamic", "report.md")
THRESHOLDS = [2, 3, 4, 6, 8, 16]
STRATEGIES = ["read", "chunk", "pread", "mmap", "tail", "mmaptail", "exact"]
TAIL = ("tail", "mmaptail", "exact")
T = 4


def pct(k, n):
    return f"{k}/{n} = {k/n*100:.0f}%" if n else "-"


def main():
    rows = list(csv.DictReader(open(CSV)))
    live = all(r.get("live_ratio") for r in rows)
    sig = "live_ratio" if live else "mmap_ratio"
    for r in rows:
        for k in ("ratio", "hunt_ratio", "mmap_ratio", sig):
            r[k] = float(r[k])
    stego = [r for r in rows if r["scenario"] == "stego"]
    benign = [r for r in rows if r["scenario"] == "benign"]
    embedded = [r for r in rows if r["scenario"] == "embedded"]
    flagged = lambda r: r.get("live_verdict", "").startswith("STEGO")
    whole = [r for r in stego if r["strategy"] not in TAIL]

    L = ["# Dynamic evaluation report\n",
         "Auto-generated by `experiments/dynamic/analyze_dynamic.py`. Signals: "
         "`hunt_ratio` = original hunt.bt (sys_exit_read only); `ratio` = "
         "read-family (read+pread+readv+preadv); `mmap_ratio` = read-family + "
         "carrier mmap bytes; `live_ratio` = the current `dynamic/hunt.bt` "
         "measured live in the kernel during the sweep.\n",
         f"Runs: **{len(rows)}** ({len(stego)} stego, {len(benign)} benign, "
         f"{len(embedded)} embedded-payload), "
         f"strategies {STRATEGIES}. ROC signal: `{sig}`"
         f"{' (live)' if live else ' (simulated; rerun with --live)'}.\n"]

    L.append("## ROC over the read:write threshold\n")
    L.append("Whole-cover = extractors that read the full carrier (read, chunk, "
             "pread, mmap); tail = extractors that read only the trailing "
             "payload region.\n")
    L.append("| Threshold | TPR all stego | TPR whole-cover | FPR benign |")
    L.append("|---|---|---|---|")
    for t in THRESHOLDS:
        tp = sum(r[sig] >= t for r in stego)
        tw = sum(r[sig] >= t for r in whole)
        fp = sum(r[sig] >= t for r in benign)
        L.append(f"| {t} | {pct(tp, len(stego))} | {pct(tw, len(whole))} | "
                 f"{pct(fp, len(benign))} |")
    L.append("")

    L.append(f"## Evasion by read strategy (stego runs, threshold {T})\n")
    cols = [("hunt_ratio", "original hunt.bt"), ("ratio", "+pread/readv"),
            ("mmap_ratio", "+mmap (sim)")]
    if live:
        cols.append(("live_ratio", "current hunt.bt (live)"))
    L.append("| Strategy | " + " | ".join(c[1] for c in cols) + " |")
    L.append("|---|" + "---|" * len(cols))
    by = defaultdict(list)
    for r in stego:
        by[r["strategy"]].append(r)
    for s in STRATEGIES:
        g = by[s]
        L.append(f"| {s} | " + " | ".join(
            pct(sum(r[c] >= T for r in g), len(g)) for c, _ in cols) + " |")
    L.append("| **all** | " + " | ".join(
        pct(sum(r[c] >= T for r in stego), len(stego)) for c, _ in cols) + " |")
    L.append("")

    L.append(f"## Tail-read gap by payload size (`{sig}`, threshold {T})\n")
    L.append("| Payload (W) | tail | mmaptail | max tail ratio |")
    L.append("|---|---|---|---|")
    for W in sorted({int(r["write_size"]) for r in stego}):
        cells = []
        for s in TAIL:
            g = [r for r in by[s] if int(r["write_size"]) == W]
            cells.append(pct(sum(r[sig] >= T for r in g), len(g)))
        mx = max(r[sig] for r in stego
                 if r["strategy"] in TAIL and int(r["write_size"]) == W)
        L.append(f"| {W} | {cells[0]} | {cells[1]} | {mx:.2f} |")
    L.append("")

    if live:
        noise = [int(r["live_read"]) - int(r["read_size"]) for r in benign]
        L.append("## Benign noise floor (live)\n")
        L.append(f"Bytes hunt.bt attributes to a benign loader beyond its own "
                 f"data read: min {min(noise)} B, max {max(noise)} B. Max benign "
                 f"ratio {max(r[sig] for r in benign):.2f}.\n")

    tp_all = sum(r[sig] >= T for r in stego)
    tp_whole = sum(r[sig] >= T for r in whole)
    tail_caught = sum(r[sig] >= T for r in stego if r["strategy"] in TAIL)
    n_tail = sum(r["strategy"] in TAIL for r in stego)
    shallow = [r for r in whole if r[sig] < T]
    if live:
        L.append(f"## Combined verdict: ratio + provenance (live)\n")
        L.append("Flagged = `STEGO-EXTRACTION` (ratio >= 4) or `STEGO-DECODE` "
                 "(exec'd ELF header never read verbatim from offset 0 of a "
                 "file).\n")
        encs = sorted({r["encoding"] for r in stego})
        L.append("| Strategy | ratio only | " +
                 " | ".join(f"combined ({e})" for e in encs) + " |")
        L.append("|---|---|" + "---|" * len(encs))
        for s in STRATEGIES:
            g = by[s]
            L.append(f"| {s} | {pct(sum(r[sig] >= T for r in g), len(g))} | " +
                     " | ".join(pct(sum(flagged(r) for r in g if r["encoding"] == e),
                                    sum(r["encoding"] == e for r in g))
                                for e in encs) + " |")
        L.append(f"| **all stego** | {pct(sum(r[sig] >= T for r in stego), len(stego))} | " +
                 " | ".join(pct(sum(flagged(r) for r in stego if r["encoding"] == e),
                                sum(r["encoding"] == e for r in stego))
                            for e in encs) + " |")
        L.append("")
        L.append("| Benign class | ratio only | combined |")
        L.append("|---|---|---|")
        for name, g in (("file loader (reads the ELF it execs)", benign),
                        ("embedded payload (ELF from own memory)", embedded)):
            L.append(f"| {name} | {pct(sum(r[sig] >= T for r in g), len(g))} | "
                     f"{pct(sum(flagged(r) for r in g), len(g))} |")
        L.append("")

    L.append("## Findings\n")
    L.append(f"- **Original hunt.bt: {pct(sum(r['hunt_ratio'] >= T for r in stego), len(stego))}"
             f"** of stego runs at threshold {T}; pread and mmap evade it.")
    L.append(f"- **Current hunt.bt: {pct(tp_whole, len(whole))} of whole-cover "
             f"extractions**, identical across read/chunk/pread/mmap; the "
             f"{len(shallow)} misses are all cover:payload = 2 (below threshold).")
    L.append(f"- **Tail reads evade the ratio: {pct(tail_caught, n_tail)} caught.** "
             f"An extractor that seeks to the trailing payload never reads the "
             f"cover, so read ~= write regardless of syscall coverage; the few "
             f"catches are page-granularity artifacts at the 1 KB payload.")
    L.append(f"- **Ratio alone: {pct(tp_all, len(stego))}**; FPR "
             f"{pct(sum(r[sig] >= T for r in benign), len(benign))}.")
    if live:
        L.append(f"- **Ratio + provenance: {pct(sum(flagged(r) for r in stego), len(stego))}"
                 f"** of stego runs, every strategy and encoding, tail reads included; "
                 f"file-loader FPR {pct(sum(flagged(r) for r in benign), len(benign))}.")
        L.append(f"- **Known FP class: embedded-payload loaders "
                 f"{pct(sum(flagged(r) for r in embedded), len(embedded))} flagged** — "
                 f"an ELF exec'd from the process's own memory has no file "
                 f"provenance, which is exactly what a decode looks like.")
    L.append("")
    open(REPORT, "w").write("\n".join(L))
    print("\n".join(L))
    print(f"\n[=] written -> {REPORT}")


if __name__ == "__main__":
    main()
